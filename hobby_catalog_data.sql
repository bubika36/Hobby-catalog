-- Felhasznalok
SELECT * FROM users;

-- Klubok
SELECT * FROM clubs;

-- Kategoriak
SELECT * FROM categories;

-- Klubok kategoriakkal
SELECT
    c.name AS clubName,
    cat.name AS categoryName
FROM clubs c
JOIN clubCategories cc
    ON c.clubId = cc.clubs_clubId
JOIN categories cat
    ON cat.categoryId = cc.categories_categoryId
ORDER BY c.name;

-- Klubok es araik
SELECT
    c.name AS clubName,
    p.adult,
    p.student
FROM clubs c
JOIN price p
    ON c.clubId = p.clubs_clubId
ORDER BY c.name;

-- Ertekelesek klubonkent
SELECT
    c.name AS clubName,
    r.rating,
    r.comment,
    r.createdAt
FROM reviews r
JOIN clubs c
    ON c.clubId = r.clubs_clubId
ORDER BY c.name, r.createdAt;

-- Uzenetek klubonkent
SELECT
    c.name AS clubName,
    u.userName,
    m.message,
    m.createdAt
FROM messages m
JOIN users u
    ON u.userId = m.users_userId
JOIN clubs c
    ON c.clubId = m.clubs_clubId
ORDER BY m.createdAt;
